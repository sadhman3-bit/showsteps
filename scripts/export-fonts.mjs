// Writes packages/core/src/export/fonts.generated.ts: the Funnel fonts (SIL Open Font License)
// that exports embed, cut down to Latin text and pinned to the weights used.
//   HTML exports: WOFF2 of Funnel Sans 400 and 600 and Funnel Display 700.
//   PDF exports: TrueType of Funnel Sans 400 and 700 and Funnel Display 800 (pdf-lib embeds
//   and subsets them again per document).
// Run: node scripts/export-fonts.mjs (output is committed; rerun when the fonts change).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import subsetFont from 'subset-font';

const root = fileURLToPath(new URL('..', import.meta.url));
const sans = readFileSync(`${root}packages/ui/assets/fonts/FunnelSans-Variable.ttf`);
const display = readFileSync(`${root}packages/ui/assets/fonts/FunnelDisplay-Variable.ttf`);

// Basic Latin, Latin-1, Latin Extended-A, punctuation, currency, arrows and a check mark.
const ranges = [
  [0x20, 0x7e],
  [0xa0, 0x17f],
  [0x2010, 0x2027],
  [0x2030, 0x203a],
  [0x20ac, 0x20ac],
  [0x2122, 0x2122],
  [0x2190, 0x2193],
  [0x2713, 0x2713],
];
let text = '';
for (const [a, b] of ranges) for (let c = a; c <= b; c++) text += String.fromCodePoint(c);

const cut = async (font, weight, targetFormat) =>
  Buffer.from(await subsetFont(font, text, { targetFormat, variationAxes: { wght: weight } }));

const out = {
  WEB_SANS_400: await cut(sans, 400, 'woff2'),
  WEB_SANS_600: await cut(sans, 600, 'woff2'),
  WEB_DISPLAY_700: await cut(display, 700, 'woff2'),
  PDF_SANS_400: await cut(sans, 400, 'truetype'),
  PDF_SANS_700: await cut(sans, 700, 'truetype'),
  PDF_DISPLAY_800: await cut(display, 800, 'truetype'),
};

const lines = [
  '// Generated by scripts/export-fonts.mjs: do not edit. Funnel Sans and Funnel Display,',
  '// Copyright 2024 The Funnel Project Authors, SIL Open Font License 1.1 (packages/ui/assets/fonts).',
  '// Base64, cut to Latin text and pinned to one weight each.',
];
for (const [name, bytes] of Object.entries(out))
  lines.push(`export const ${name} = '${bytes.toString('base64')}';`);
writeFileSync(`${root}packages/core/src/export/fonts.generated.ts`, `${lines.join('\n')}\n`);
for (const [name, bytes] of Object.entries(out))
  console.log(`${name.padEnd(16)} ${(bytes.length / 1024).toFixed(1)} KB`);
